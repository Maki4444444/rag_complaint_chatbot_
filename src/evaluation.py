"""
src/evaluation.py

Systematic RAG evaluation harness (replaces the qualitative-only checks in
notebooks/rag_pipeline.ipynb with a fixed, repeatable, quantitative pass).

What it does:
    1. Loads a fixed question set (data/eval_questions.json) spanning all
       four product categories.
    2. Runs each question through the real retrieve() + generate_answer()
       pipeline (same code path as app.py -- not a separate reimplementation).
    3. Scores each answer on two axes using an LLM-as-judge, on a 1-5 rubric:
         - retrieval_relevance: are the retrieved chunks actually relevant
           to the question?
         - faithfulness: does the generated answer stay grounded in the
           retrieved chunks, with no unsupported claims?
    4. Logs a timestamped, per-question results file to eval_results/, and
       appends a one-line run summary to eval_results/history.csv so runs
       can be compared over time against a baseline.

Usage:
    python -m src.evaluation \
        --vector-store ./vector_store_full \
        --collection complaints_full \
        --questions data/eval_questions.json \
        --resume

Defaults to vector_store_full/complaints_full (the pre-built full-scale
store, ~1.37M chunks / ~464K complaints, ingested by
src/build_full_index.py) -- per the Task 3 brief, evaluation should run
against the complete dataset, not the Task 2 sample store. Override
--vector-store/--collection to vector_store_sample/complaints_sample for
a fast local smoke test instead, e.g. while iterating on the harness
itself before spending API credits against the full store.

The judge uses its own, smaller/cheaper HF model (JUDGE_MODEL below),
separate from the generation model in src/generator.py -- judging 18
questions on the same 7B model used for generation doubles API spend
for no real accuracy benefit on a simple 2-field rubric. Override with
--judge-model if you want to try a different one.

Judge scoring is a heuristic aid, not a substitute for eyeballing
results -- see docs/PROGRESS_LOG.md for the manual-review step taken
before trusting any aggregate number.

--resume skips any question that already has a *complete* result
(generation succeeded AND judging succeeded) in the most recent
eval_results/results_*.json file, and carries that row forward into the
new results/history entry unchanged. This avoids re-paying API credits
for rows that already scored successfully in a prior, interrupted run.
"""
import argparse
import csv
import glob
import json
import os
import re
from datetime import datetime, timezone
from pathlib import Path

from src.embedding import load_embedding_model, EMBEDDING_MODEL_NAME
from src.retriever import load_vector_store, build_retriever, RetrievalError
from src.generator import build_llm_client, generate_answer

REPO_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_QUESTIONS_PATH = REPO_ROOT / "data" / "eval_questions.json"
RESULTS_DIR = REPO_ROOT / "eval_results"
HISTORY_CSV = RESULTS_DIR / "history.csv"

FAITHFULNESS_TARGET = 0.85  # matches the success metric: >=85% of responses

# A small, cheap instruct model for judging. Scoring a fixed 2-field rubric
# is a much easier task than open-ended generation, so a much smaller model
# is normally sufficient -- and it draws from a separate quota/rate limit
# than whatever model src/generator.py uses for generation.
JUDGE_MODEL = "Qwen/Qwen2.5-1.5B-Instruct"

JUDGE_PROMPT_TEMPLATE = """You are a strict, impartial evaluator scoring a RAG \
(Retrieval-Augmented Generation) system for a financial complaints chatbot.

Question asked by the user:
{question}

Retrieved complaint excerpts given to the system as context:
{context}

Answer generated by the system:
{answer}

Score the answer on exactly two dimensions, each from 1 (worst) to 5 (best):

1. retrieval_relevance: Are the retrieved excerpts actually relevant to the \
question? (5 = highly relevant and on-topic, 1 = irrelevant/off-topic)
2. faithfulness: Does the answer stay strictly grounded in the retrieved \
excerpts, with no invented facts, numbers, or claims not supported by the \
context? (5 = fully grounded, 1 = largely fabricated or unsupported)

Respond with ONLY a single JSON object, no other text, in exactly this form:
{{"retrieval_relevance": <int 1-5>, "faithfulness": <int 1-5>, "comment": "<one sentence justification>"}}
"""


def load_questions(path: Path = DEFAULT_QUESTIONS_PATH) -> list:
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)


def _extract_json(text: str) -> dict:
    """
    Judge models occasionally wrap JSON in prose or code fences despite
    instructions. Pull out the first {...} block and parse it, rather than
    trusting the raw response verbatim.
    """
    match = re.search(r"\{.*\}", text, re.DOTALL)
    if not match:
        raise ValueError(f"No JSON object found in judge response: {text!r}")
    return json.loads(match.group(0))


def find_latest_results() -> Path | None:
    """Returns the most recent eval_results/results_*.json file, or None
    if no run has completed yet."""
    candidates = sorted(glob.glob(str(RESULTS_DIR / "results_*.json")))
    return Path(candidates[-1]) if candidates else None


def load_carry_forward_rows(path: Path) -> dict:
    """
    Loads a previous results file and returns a dict of {question_id: row}
    for only the rows that fully succeeded: generation did not fall back
    (generation_error is False) AND the judge scored it (judge_error is
    None). Rows that failed generation, failed judging, or hit a
    RetrievalError are NOT carried forward -- they need to be retried.
    """
    if path is None or not path.exists():
        return {}

    with open(path, "r", encoding="utf-8") as f:
        data = json.load(f)

    carry_forward = {}
    for row in data.get("rows", []):
        if row.get("generation_error") is False and row.get("judge_error") is None:
            carry_forward[row["id"]] = row
    return carry_forward


def judge_answer(client, question: str, context_block: str, answer: str) -> dict:
    """
    Calls the LLM-as-judge to score one (question, context, answer) triple.

    Returns a dict with retrieval_relevance (int), faithfulness (int),
    comment (str). On any parsing/API failure, returns None-valued scores
    with the raw error in "comment" so a failed judge call is visible in
    the results rather than silently treated as a 0.
    """
    prompt = JUDGE_PROMPT_TEMPLATE.format(
        question=question,
        context=context_block or "(no context retrieved)",
        answer=answer,
    )
    try:
        response = client.chat_completion(
            messages=[{"role": "user", "content": prompt}],
            max_tokens=150,
        )
        raw = (response.choices[0].message.content or "").strip()
        parsed = _extract_json(raw)
        return {
            "retrieval_relevance": int(parsed["retrieval_relevance"]),
            "faithfulness": int(parsed["faithfulness"]),
            "comment": str(parsed.get("comment", "")),
            "judge_error": None,
        }
    except Exception as exc:  # noqa: BLE001 -- a failed judge call must not crash the run
        return {
            "retrieval_relevance": None,
            "faithfulness": None,
            "comment": "",
            "judge_error": str(exc),
        }


def run_evaluation(
    vector_store_dir: str,
    collection_name: str,
    questions_path: Path = DEFAULT_QUESTIONS_PATH,
    top_k: int = 5,
    judge_model: str = JUDGE_MODEL,
    generation_model: str | None = None,
    carry_forward: dict | None = None,
) -> dict:
    """
    Runs the full evaluation harness and returns a results dict. Also
    writes the results to disk (see save_results()).

    Any question id present in `carry_forward` is skipped entirely (no
    retrieval, no generation, no judge call) and that row is reused
    as-is -- see load_carry_forward_rows() / --resume.
    """
    carry_forward = carry_forward or {}
    questions = load_questions(questions_path)

    # Only pay for model/store/client setup if there's actually work to do.
    remaining = [q for q in questions if q["id"] not in carry_forward]

    embed_model = None
    collection = None
    retrieve = None
    llm_client = None
    judge_client = None

    if remaining:
        print("Loading embedding model...")
        embed_model = load_embedding_model(EMBEDDING_MODEL_NAME)

        print("Loading vector store...")
        collection = load_vector_store(vector_store_dir, collection_name)
        retrieve = build_retriever(collection, model=embed_model)

        gen_kwargs = {"model": generation_model} if generation_model else {}
        print(f"Connecting to generation LLM"
              f"{f' ({generation_model})' if generation_model else ''}...")
        llm_client = build_llm_client(**gen_kwargs)

        print(f"Connecting to judge LLM ({judge_model})...")
        judge_client = build_llm_client(model=judge_model)

    rows = []
    for item in questions:
        qid, category, question = item["id"], item["category"], item["question"]

        if qid in carry_forward:
            print(f"[{qid}] skipped (resuming from prior successful run)")
            rows.append(carry_forward[qid])
            continue

        print(f"[{qid}] {question}")

        try:
            chunks = retrieve(question, top_k=top_k)
        except RetrievalError as exc:
            rows.append({
                "id": qid, "category": category, "question": question,
                "answer": None, "retrieved_sources": [],
                "retrieval_relevance": None, "faithfulness": None,
                "comment": f"Retrieval failed: {exc}", "judge_error": str(exc),
                "generation_error": False,
            })
            continue

        result = generate_answer(llm_client, question, chunks)
        judge = judge_answer(judge_client, question, result["context_block"], result["answer"])

        rows.append({
            "id": qid,
            "category": category,
            "question": question,
            "answer": result["answer"],
            "retrieved_sources": [
                {"complaint_id": c["complaint_id"], "product_category": c["product_category"],
                 "company": c.get("company", ""), "issue": c.get("issue", ""),
                 "similarity_score": c["similarity_score"], "excerpt": c["chunk_text"][:200]}
                for c in chunks[:2]  # keep the results file readable; top-2 per the report table format
            ],
            "generation_error": result["error"],
            **judge,
        })

    results = {
        "run_timestamp": datetime.now(timezone.utc).isoformat(),
        "vector_store_dir": vector_store_dir,
        "collection_name": collection_name,
        "top_k": top_k,
        "judge_model": judge_model,
        "generation_model": generation_model or "default (src.generator.MODEL)",
        "num_questions": len(rows),
        "num_resumed": len(carry_forward),
        "rows": rows,
    }
    return results


def summarize(results: dict) -> dict:
    """Computes aggregate metrics from a results dict."""
    scored = [r for r in results["rows"] if r["faithfulness"] is not None]
    n_scored = len(scored)
    n_total = results["num_questions"]

    if n_scored == 0:
        return {
            "n_total": n_total, "n_scored": 0,
            "avg_retrieval_relevance": None, "avg_faithfulness": None,
            "pct_faithful_ge_4": None, "meets_faithfulness_target": False,
        }

    avg_relevance = sum(r["retrieval_relevance"] for r in scored) / n_scored
    avg_faithfulness = sum(r["faithfulness"] for r in scored) / n_scored
    # "Answer stays grounded ... in at least 85% of evaluated responses" --
    # treat a faithfulness score of 4 or 5 as "grounded, no unsupported claims".
    n_faithful = sum(1 for r in scored if r["faithfulness"] >= 4)
    pct_faithful = n_faithful / n_scored

    return {
        "n_total": n_total,
        "n_scored": n_scored,
        "avg_retrieval_relevance": round(avg_relevance, 2),
        "avg_faithfulness": round(avg_faithfulness, 2),
        "pct_faithful_ge_4": round(pct_faithful, 3),
        "meets_faithfulness_target": pct_faithful >= FAITHFULNESS_TARGET,
    }


def save_results(results: dict, summary: dict) -> Path:
    """Writes the full results JSON and appends a summary row to history.csv."""
    RESULTS_DIR.mkdir(exist_ok=True)

    ts = results["run_timestamp"].replace(":", "-")
    out_path = RESULTS_DIR / f"results_{ts}.json"
    with open(out_path, "w", encoding="utf-8") as f:
        json.dump({"summary": summary, **results}, f, indent=2)

    is_new = not HISTORY_CSV.exists()
    with open(HISTORY_CSV, "a", newline="", encoding="utf-8") as f:
        writer = csv.writer(f)
        if is_new:
            writer.writerow([
                "run_timestamp", "n_total", "n_scored",
                "avg_retrieval_relevance", "avg_faithfulness",
                "pct_faithful_ge_4", "meets_faithfulness_target", "results_file",
            ])
        writer.writerow([
            results["run_timestamp"], summary["n_total"], summary["n_scored"],
            summary["avg_retrieval_relevance"], summary["avg_faithfulness"],
            summary["pct_faithful_ge_4"], summary["meets_faithfulness_target"],
            out_path.name,
        ])

    return out_path


def to_markdown_table(results: dict, max_rows: int = None) -> str:
    """Renders the evaluation table format required for the report:
    Question, Generated Answer, Retrieved Sources (1-2), Quality Score, Comments."""
    rows = results["rows"][:max_rows] if max_rows else results["rows"]
    lines = [
        "| Question | Generated Answer | Retrieved Sources | Quality Score | Comments/Analysis |",
        "|---|---|---|---|---|",
    ]
    for r in rows:
        sources = "; ".join(
            f"{s['product_category']} #{s['complaint_id']} ({s['similarity_score']:.2f})"
            for s in r.get("retrieved_sources", [])
        ) or "none retrieved"
        answer = (r["answer"] or "").replace("\n", " ")[:150]
        score = (
            f"R:{r['retrieval_relevance']}/F:{r['faithfulness']}"
            if r["faithfulness"] is not None else "N/A (judge error)"
        )
        comment = r.get("comment") or r.get("judge_error") or ""
        lines.append(f"| {r['question']} | {answer}... | {sources} | {score} | {comment} |")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description="Run the RAG evaluation harness.")
    parser.add_argument("--vector-store", default="./vector_store_full")
    parser.add_argument("--collection", default="complaints_full")
    parser.add_argument("--questions", default=str(DEFAULT_QUESTIONS_PATH))
    parser.add_argument("--top-k", type=int, default=5)
    parser.add_argument("--model", default=None,
                         help="HF model id for answer generation, overriding "
                              "src.generator.MODEL (Qwen/Qwen2.5-7B-Instruct). "
                              "Use this to switch providers if you hit a "
                              "quota/402 error, e.g. a smaller/cheaper model.")
    parser.add_argument("--judge-model", default=JUDGE_MODEL,
                         help="HF model id used for LLM-as-judge scoring "
                              "(separate from the generation model).")
    parser.add_argument("--resume", action="store_true",
                         help="Skip questions that already succeeded "
                              "(generation + judging) in the most recent "
                              "eval_results/results_*.json file.")
    parser.add_argument("--resume-from", default=None,
                         help="Explicit results file to resume from "
                              "(defaults to the most recent one).")
    args = parser.parse_args()

    carry_forward = {}
    if args.resume:
        resume_path = Path(args.resume_from) if args.resume_from else find_latest_results()
        if resume_path is None:
            print("--resume was set but no prior eval_results/results_*.json "
                  "was found -- running all questions fresh.")
        else:
            carry_forward = load_carry_forward_rows(resume_path)
            print(f"Resuming from {resume_path.name}: "
                  f"{len(carry_forward)} question(s) already scored, will be skipped.")

    results = run_evaluation(
        vector_store_dir=args.vector_store,
        collection_name=args.collection,
        questions_path=Path(args.questions),
        top_k=args.top_k,
        judge_model=args.judge_model,
        generation_model=args.model,
        carry_forward=carry_forward,
    )
    summary = summarize(results)
    out_path = save_results(results, summary)

    print("\n=== Evaluation Summary ===")
    print(json.dumps(summary, indent=2))
    print(f"\nFull results written to: {out_path}")
    print(f"History log updated at:  {HISTORY_CSV}")
    print("\n--- Markdown table (for report) ---\n")
    print(to_markdown_table(results))


if __name__ == "__main__":
    main()